#!/usr/bin/env node
/*
 * Builds app/blush.css from the Blush Astro theme's stylesheet and the <style>
 * blocks of the components that were ported.
 *
 *   node scripts/build-blush-css.mjs /path/to/xoco-blush
 *
 * The live site already carries the Magzin template's global CSS (bootstrap grid,
 * main.css), so the Blush rules must not leak into it, nor it into them:
 *   - every class gets a "bl-" prefix (the JSX writes them through lib/blush.ts: b())
 *   - every rule is scoped under the .blush wrapper; :root / html / body map to it
 *   - Tailwind-only directives and the theme's own @font-face are dropped (Inter is
 *     already loaded by the site)
 * The output is committed, so a build never depends on the theme repo.
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const themeDir = path.resolve(process.argv[2] || '../xoco-blush-bestlooking');
const PREFIX = 'bl-';
const SCOPE = '.blush';

const styleBlocks = [
  'src/components/PopularRail.astro',
  'src/components/ui/PostMeta.astro',
  'src/components/SiteFooter.astro',
  'src/components/HomeCover.astro',
  'src/components/ProductSlider.astro',
  'src/components/SectionHeader.astro',
  'src/components/SaveButton.astro',
  'src/components/ShareButton.astro',
  'src/components/CoverStory.astro',
  'src/components/PostRow.astro',
];

function extractStyles(file) {
  const src = fs.readFileSync(path.join(themeDir, file), 'utf8');
  return [...src.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
}

/* Split a selector list on top-level commas. */
function splitList(sel) {
  const out = [];
  let depth = 0, cur = '';
  for (const ch of sel) {
    if (ch === '(' || ch === '[') depth++;
    if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.trim()).filter(Boolean);
}

/* Prefix class names, leaving attribute selectors and strings alone. */
function prefixClasses(sel) {
  let out = '', i = 0;
  while (i < sel.length) {
    const ch = sel[i];
    if (ch === '[') { const j = sel.indexOf(']', i); out += sel.slice(i, j + 1); i = j + 1; continue; }
    if (ch === '.') {
      const m = /^\.(-?[_a-zA-Z][\w-]*)/.exec(sel.slice(i));
      if (m) { out += '.' + PREFIX + m[1]; i += m[0].length; continue; }
    }
    out += ch; i++;
  }
  return out;
}

function scopeSelector(raw) {
  let sel = raw.replace(/:global\(([^)]*)\)/g, '$1');
  sel = prefixClasses(sel);
  // dark theme / root
  sel = sel.replace(/^:root\[data-theme="dark"\]/, `${SCOPE}[data-theme="dark"]`);
  sel = sel.replace(/^:root\b/, SCOPE);
  sel = sel.replace(/^html\b/, SCOPE);
  if (/^body\b/.test(sel)) sel = sel.replace(/^body/, SCOPE);
  if (sel.startsWith(SCOPE)) return sel;
  if (sel === '*' || sel.startsWith('*')) return `${SCOPE} ${sel}, ${SCOPE}${sel === '*' ? '' : ''}`.replace(/, \.blush$/, '');
  return `${SCOPE} ${sel}`;
}

const raw = [
  fs.readFileSync(path.join(themeDir, 'src/styles/global.css'), 'utf8'),
  ...styleBlocks.map(extractStyles),
].join('\n');

const root = postcss.parse(raw);

root.walkAtRules((at) => {
  if (at.name === 'import' || at.name === 'source' || at.name === 'theme' || at.name === 'font-face') at.remove();
  if (at.name === 'keyframes') at.params = PREFIX + at.params;
});
root.walkDecls((d) => {
  /* animation names follow the renamed keyframes */
  if (d.prop === 'animation' || d.prop === 'animation-name') {
    d.value = d.value.replace(/\b(?!none\b)([a-z][\w-]*)\b(?=\s|$|,)/g, (m, name, off, s) => m);
  }
});
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selector = splitList(rule.selector).map(scopeSelector).join(',\n');
});

/* Keyframe names: collect and rewrite references. */
const names = new Set();
root.walkAtRules('keyframes', (a) => names.add(a.params.replace(PREFIX, '')));
root.walkDecls((d) => {
  if (!/^animation(-name)?$/.test(d.prop)) return;
  d.value = d.value.replace(/[A-Za-z_][\w-]*/g, (w) => (names.has(w) ? PREFIX + w : w));
});

const header = `/* GENERATED by scripts/build-blush-css.mjs from the Blush theme; do not edit by hand. */\n`;
fs.writeFileSync('app/blush.css', header + root.toString());
console.log('wrote app/blush.css', (fs.statSync('app/blush.css').size / 1024).toFixed(0) + 'KB');
